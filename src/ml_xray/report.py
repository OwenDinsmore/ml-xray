_DOCUMENT = _ENV.from_string("""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{{ title }}</title>
<style>{{ css }}</style></head>
<body>
<h1>{{ title }}</h1>
{{ body }}
<footer>Generated by ml-xray</footer>
</body></html>
""")


def _document(title: str, body: str) -> str:
    # `body` is already-rendered, trusted HTML from our own section templates.
    from markupsafe import Markup

    return _DOCUMENT.render(title=title, css=_BASE_CSS, body=Markup(body))


