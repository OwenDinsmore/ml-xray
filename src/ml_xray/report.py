def _finding_view(f) -> type:
    keys = [k for k in f.detail if k != "kind"]
    parts = []
    for k in keys[:4]:
        v = f.detail[k]
        if isinstance(v, float):
            parts.append(f"{k}={v:.4g}")
        elif isinstance(v, (int, str)):
            parts.append(f"{k}={v}")
    view = {
        "severity": f.severity,
        "check": f.check,
        "column": f.column,
        "message": f.message,
        "detail_summary": " · ".join(parts),
        "row_count": f"{len(f.rows)} rows" if f.rows else "",
    }
    return type("V", (), view)


def lint_section(report: LintReport) -> str:
    """Render the lint report as an HTML body fragment (no ``<html>`` wrapper)."""
    ordered = report.worst(n=len(report.findings)) if report.findings else []
    views = [_finding_view(f) for f in ordered]
    return _LINT_SECTION.render(meta=report.meta, counts=report.counts(), findings=views)


def lint_report_html(report: LintReport) -> str:
    """Render a :class:`~ml_xray.lint.linter.LintReport` to a full HTML document."""
    return _document("ml-xray — dataset lint report", lint_section(report))


