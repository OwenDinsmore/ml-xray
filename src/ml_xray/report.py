"""HTML report rendering.

Every result object in ``ml-xray`` can emit a self-contained HTML section. This
module holds the :mod:`jinja2` templates and helpers that render each section
(lint / slices / embed) and stitch them into a single file with no external asset
requests (all CSS is inlined). Optional matplotlib figures are produced lazily and
degrade to a clear error when no plotting backend is installed.
"""

