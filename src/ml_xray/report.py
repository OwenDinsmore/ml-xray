def _require_matplotlib():
    from ._optional import optional_import

    plt = optional_import("matplotlib")
    if plt is None:
        raise ImportError('Plotting needs matplotlib. Install it with: pip install "ml-xray[viz]"')
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as pyplot

    return pyplot


def slice_bar_figure(report: SliceReport):
    """Return a matplotlib bar chart of the worst slices' deltas."""
    plt = _require_matplotlib()
    slices = report.slices[:15][::-1]
    labels = [s.describe() for s in slices]
    deltas = [s.delta for s in slices]
    fig, ax = plt.subplots(figsize=(8, max(2, 0.4 * len(slices) + 1)))
    ax.barh(labels, deltas, color=["#b3261e" if d < 0 else "#1e7d34" for d in deltas])
    ax.axvline(0, color="#888", linewidth=0.8)
    ax.set_xlabel(f"delta vs baseline ({report.metric})")
    ax.set_title("Worst-performing slices")
    fig.tight_layout()
    return fig


def embed_projection_figure(report: EmbedDiffReport, *, seed: int = 0):
    """Return a linked before/after 2D scatter of the two embedding spaces."""
    plt = _require_matplotlib()
    if report._emb_a is None or report._emb_b is None:
        raise RuntimeError("source embeddings were not retained on the report")
    from .embed.project import project_2d

    proj_a, proj_b = project_2d(
        report._emb_a, report._emb_b, projector=report_projector(report), seed=seed
    )
    drift = report.per_point_drift
    fig, axes = plt.subplots(1, 2, figsize=(10, 4.5), sharex=True, sharey=True)
    for ax, proj, title in ((axes[0], proj_a, "A (before)"), (axes[1], proj_b, "B (after)")):
        sc = ax.scatter(proj[:, 0], proj[:, 1], c=drift, cmap="magma", s=12)
        ax.set_title(title)
        ax.set_xticks([])
        ax.set_yticks([])
    fig.colorbar(sc, ax=axes, label="neighborhood drift", fraction=0.046)
    fig.suptitle("Embedding spaces (colored by per-point drift)")
    return fig


def report_projector(report: EmbedDiffReport) -> str:
    """Best-effort projector choice for a report (kept simple: auto)."""
    return "auto"


def _projection_data_uri(report: EmbedDiffReport) -> str | None:
    """Render the projection figure to a base64 PNG data URI, or None if unavailable."""
    try:
        fig = embed_projection_figure(report)
    except (ImportError, RuntimeError):
        return None
    import base64
    import io

    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=110, bbox_inches="tight")
    import matplotlib.pyplot as plt

    plt.close(fig)
    encoded = base64.b64encode(buf.getvalue()).decode("ascii")
    return f"data:image/png;base64,{encoded}"
